"""Integração: migrações do Alembic (upgrade, downgrade e paridade com os modelos)."""

import pytest
from alembic import command
from alembic.config import Config as ConfigAlembic
from sqlalchemy import Engine, inspect

pytestmark = pytest.mark.integracao

TABELAS = {"conjunto_trechos_criticos", "trecho_critico", "calculo_indice", "calculo_indice_hora"}


def tabelas_do_servico(engine: Engine) -> set[str]:
    """Tabelas do serviço presentes no banco (ignora a alembic_version)."""
    return set(inspect(engine).get_table_names()) & TABELAS


def test_migracoes_downgrade_base_e_upgrade_head_criam_e_removem_tabelas(
    engine_teste: Engine, alembic_teste: ConfigAlembic
) -> None:
    # Act e Assert: base remove tudo.
    command.downgrade(alembic_teste, "base")
    assert tabelas_do_servico(engine_teste) == set()

    # Act e Assert: 0001 cria só as tabelas dos trechos.
    command.upgrade(alembic_teste, "0001")
    assert tabelas_do_servico(engine_teste) == {"conjunto_trechos_criticos", "trecho_critico"}

    # Act e Assert: head cria as quatro.
    command.upgrade(alembic_teste, "head")
    assert tabelas_do_servico(engine_teste) == TABELAS


def test_migracoes_constraints_com_nomes_previsiveis(engine_teste: Engine) -> None:
    # Arrange
    inspetor = inspect(engine_teste)

    # Act
    unicas = {u["name"] for u in inspetor.get_unique_constraints("trecho_critico")}
    checks = {c["name"] for c in inspetor.get_check_constraints("calculo_indice")}
    estrangeiras = inspetor.get_foreign_keys("calculo_indice_hora")

    # Assert
    assert "uq_trecho_critico_conjunto_id_posicao" in unicas
    assert "ck_calculo_indice_componente_sinistro_0_a_100" in checks
    assert "ck_calculo_indice_faixa_risco_valida" in checks
    assert estrangeiras[0]["options"].get("ondelete") == "CASCADE"


def test_alembic_check_modelos_iguais_as_migracoes(
    engine_teste: Engine, alembic_teste: ConfigAlembic
) -> None:
    # Act e Assert: lança AutogenerateDiffsDetected se os modelos divergirem das migrações.
    command.check(alembic_teste)
